// src/lib/supabase.ts — the only door to the database (SPEC §6 + §7).
// Components never import this file directly (G3): only SpotContext (owned by
// App.tsx) calls the three API functions below.
//
// Three hard-won gotchas baked in (all verified against the live schema):
//   1. Client creation is wrapped in try/catch — a missing/malformed key must
//      not blank the app; `supabase` becomes null and the functions throw a
//      friendly, recoverable error instead of crashing the JS thread.
//   2. `loadApprovedSpots()` paginates 1000 rows at a time — PostgREST silently
//      caps responses at ~1000 rows, so a plain `.select('*')` drops the rest
//      with NO error (the data would just be missing; SPEC §7, G7).
//   3. `insertPendingSpot()` never adds `.select()` — reading back a pending
//      row through the anon SELECT policy fails the WHOLE insert with 42501
//      (anon may only SELECT approved rows). A locally built row is returned
//      instead; the database id only exists after the owner approves the spot.
import { createClient, type SupabaseClient } from '@supabase/supabase-js';
import * as Crypto from 'expo-crypto';
import { SUPABASE_ANON_KEY, SUPABASE_URL } from './config';

// §6 Frozen data contract — field names are exactly the `spots` columns.
// Do not rename, add, or drop. The compiler enforces what review used to.
export type SpotType = 'masjid_besar' | 'musala' | 'terminal' | 'spbu' | 'rest_area';

export type WaterValue = 'kran_mandi' | 'wudhu_only' | 'air_isi' | 'tidak_ada';

export interface SPOT {
  id: string;
  name: string;
  type: SpotType;
  lat: number;
  lng: number;
  water: WaterValue | null;
  hours: string | null;
  bike_parking: boolean;
  women_friendly: boolean | null;
  notes: string | null;
  status: 'approved' | 'pending';
  source: 'osm' | 'playbook' | 'user';
  last_verified_at: string | null;
  created_at: string;
}

// Form payload (AddSpotSheet → App → addPending). Empty strings become null at
// the payload boundary (G4) — the database never stores ''.
export type SpotPayload = {
  name: string;
  type: SpotType;
  lat: number;
  lng: number;
  water: WaterValue | null;
  hours: string | null;
  bike_parking: boolean;
  women_friendly: boolean | null;
  notes: string | null;
};

// Client or null. Null means "not configured" (OQ-B pending) — the app stays
// usable (degraded) instead of crashing on boot.
export const supabase: SupabaseClient | null = (() => {
  if (!SUPABASE_URL || !SUPABASE_ANON_KEY) return null;
  try {
    return createClient(SUPABASE_URL, SUPABASE_ANON_KEY);
  } catch {
    // Malformed URL / invalid options → degraded mode, not a crash.
    return null;
  }
})();

// Guard used by every API function: when Supabase is not configured the error
// is explicit and recoverable (App shows its failure toast; no blank screen).
function requireClient(): SupabaseClient {
  if (!supabase) {
    throw new Error(
      'Supabase belum dikonfigurasi — isi EXPO_PUBLIC_SUPABASE_URL dan ' +
        'EXPO_PUBLIC_SUPABASE_ANON_KEY di .env (OQ-B).',
    );
  }
  return supabase;
}

// Approved rows only (anon SELECT policy enforces the same filter server-side;
// the explicit .eq keeps the intent in code and the result deterministic).
export async function loadApprovedSpots(): Promise<SPOT[]> {
  const client = requireClient();
  const PAGE_SIZE = 1000;
  const rows: SPOT[] = [];
  for (let start = 0; ; start += PAGE_SIZE) {
    const { data, error } = await client
      .from('spots')
      .select('*')
      .eq('status', 'approved')
      .range(start, start + PAGE_SIZE - 1);
    if (error) throw new Error(`Gagal memuat spot: ${error.message}`);
    // Untyped anon client → cast at the boundary; SPOT is the frozen contract.
    const page: SPOT[] = (data ?? []) as SPOT[];
    rows.push(...page);
    if (page.length < PAGE_SIZE) break; // last (short) page reached
  }
  return rows;
}

// Insert pending/user — NO `.select()`. The 42501 trap: chaining `.select()`
// makes PostgREST read the row back under the anon SELECT policy (approved
// only), which fails the entire insert even though the row was written.
// The returned row is locally built: `id` is a crypto UUID used ONLY as a
// display/list key — it is not a database id (the real uuid is generated by
// Postgres; a pending row is invisible to this client until approved).
export async function insertPendingSpot(payload: SpotPayload): Promise<SPOT> {
  const client = requireClient();
  const { error } = await client
    .from('spots')
    .insert({ ...payload, status: 'pending', source: 'user' });
  if (error) throw new Error(`Gagal mengirim spot: ${error.message}`);
  return {
    ...payload,
    id: Crypto.randomUUID(),
    status: 'pending',
    source: 'user',
    last_verified_at: null,
    created_at: new Date().toISOString(),
  };
}

// `Masih ada ✓` write path. rpc returns raw `false` when the bump is refused
// (rate limit 1/spot/hour — see supabase/functions/bump_verified.sql; also
// false for pending/missing ids). The typed wrapper converts the raw boolean
// into `{ ok, spot }` so callers CANNOT mistake a refused bump for success
// (G2 — the UI never lies). Anything that is not literally `true` is failure.
export async function bumpVerified(
  spotId: string,
): Promise<{ ok: boolean; spot: SPOT | null }> {
  const client = requireClient();
  const { data, error } = await client.rpc('bump_verified', { spot_id: spotId });
  if (error) throw new Error(`Gagal menyimpan verifikasi: ${error.message}`);
  if (data !== true) return { ok: false, spot: null };

  // The bump only touches approved rows, so the anon SELECT policy allows
  // reading the updated row back (last_verified_at is fresh here).
  const { data: row, error: selectError } = await client
    .from('spots')
    .select('*')
    .eq('id', spotId)
    .maybeSingle();
  if (selectError) throw new Error(`Gagal memuat spot terverifikasi: ${selectError.message}`);
  return { ok: true, spot: (row as SPOT | null) ?? null };
}
